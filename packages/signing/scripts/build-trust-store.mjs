#!/usr/bin/env node
/**
 * Generate `src/trust-store.generated.ts` from the vendored ICP-Brasil trust
 * anchors under `trust-store/*.crt`.
 *
 * The API is esbuild-bundled and its `src/` is pruned at deploy, so a runtime
 * `readdirSync(trust-store)` returns empty. Baking the PEM into an imported TS
 * constant makes the anchors travel with the bundle.
 *
 * Run after `fetch-icp-brasil-trust-store.mjs` (which downloads + hash-verifies
 * the official ITI bundle on a gov.br-reachable host) and commit both outputs.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const trustStoreDir = join(here, "..", "trust-store");
const outFile = join(here, "..", "src", "trust-store.generated.ts");

let pem = "";
let count = 0;
try {
  for (const entry of readdirSync(trustStoreDir).sort()) {
    if (!/\.(crt|cer|pem)$/i.test(entry)) continue;
    const content = readFileSync(join(trustStoreDir, entry), "utf8").trim();
    if (content) {
      pem += content + "\n";
      count += 1;
    }
  }
} catch {
  // Trust store not populated yet — emit an empty constant (chain validation
  // stays "unavailable" rather than failing the build).
}

const header = `// AUTO-GENERATED by scripts/build-trust-store.mjs — do not edit by hand.
//
// Concatenated PEM of the ICP-Brasil trust anchors vendored under
// \`trust-store/*.crt\` (the official ITI AC-Raiz bundle). Imported (not read
// from disk) so it survives the API's esbuild bundling + \`src/\` pruning.
`;

writeFileSync(
  outFile,
  `${header}export const ICP_BRASIL_TRUST_STORE_PEM = ${JSON.stringify(pem)};\n`,
);

console.log(
  `Wrote ${outFile} from ${count} certificate file(s) (${pem.length} bytes of PEM).`,
);
