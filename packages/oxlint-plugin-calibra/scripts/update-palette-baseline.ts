// Regenerates src/lib/palette-baseline.ts: the exact number of raw Tailwind
// palette colour classes each feature file still carries. Run after migrating
// a file to status-tone / theme tokens so its allowance shrinks with it:
//
//   pnpm --filter @calibra-facil/oxlint-plugin-calibra baseline:palette
//
// The baseline test fails if a count here differs from the file's real count,
// so the allowance can only move down.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { countRawPaletteClasses } from "../src/lib/palette.ts";
import { collectFeatureFiles } from "../src/lib/palette-scan.ts";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = dirname(dirname(packageRoot));

const entries = collectFeatureFiles(repoRoot)
  .map((file) => ({
    path: relative(repoRoot, file).replaceAll("\\", "/"),
    count: countRawPaletteClasses(readFileSync(file, "utf8")),
  }))
  .filter((entry) => entry.count > 0)
  .toSorted((a, b) => a.path.localeCompare(b.path));

const body = entries
  .map((entry) => `  [${JSON.stringify(entry.path)}, ${entry.count}],`)
  .join("\n");

writeFileSync(
  join(packageRoot, "src", "lib", "palette-baseline.ts"),
  `import type { Baseline } from "./rule-support.ts";

// Generated by scripts/update-palette-baseline.ts. Do not edit by hand.
export const PALETTE_BASELINE: Baseline = new Map<string, number>([
${body}
]);
`,
);

const total = entries.reduce((sum, entry) => sum + entry.count, 0);
console.log(`${entries.length} files, ${total} raw palette classes`);
