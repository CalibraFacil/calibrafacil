/**
 * Renders the generated part of docs/architecture/tenancy.md from the schema
 * (see tenancy.ts). The document keeps its prose by hand; only the block between
 * the markers below is rewritten, by `pnpm --dir packages/db tenancy:doc`, and a
 * test fails when the block on disk differs from what the schema says today.
 */
import {
  ORGANIZATION_BACKFILL,
  classifyTables,
  listTenancy,
  parentPathOf,
  unpairedPointers,
  type ReferentialAction,
} from "./tenancy";

const TENANCY_BEGIN = "<!-- BEGIN GENERATED: tenancy -->";
const TENANCY_END = "<!-- END GENERATED: tenancy -->";

const ACTION_LABEL: Record<ReferentialAction, string> = {
  cascade: "CASCADE",
  restrict: "RESTRICT",
  "no action": "NO ACTION",
  "set null": "SET NULL",
  "set default": "SET DEFAULT",
};

function code(text: string): string {
  return `\`${text}\``;
}

function renderGlobal(): string[] {
  const { global } = classifyTables();
  return [
    "| Table | Why it has no organization column |",
    "| --- | --- |",
    ...global.map(({ table, reason }) => `| ${code(table.name)} | ${reason} |`),
    "",
  ];
}

function renderBackfilled(): string[] {
  const tenancy = new Map(listTenancy().map((table) => [table.name, table]));
  const lines = [
    "| Table | Parent path to the organization | Pointer | Organization FK | Composite keys |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const entry of ORGANIZATION_BACKFILL) {
    const table = tenancy.get(entry.table);
    const column = table?.tenantColumns.find(
      (candidate) => candidate.name === "organization_id",
    );
    const path = [...parentPathOf(entry.table), "organization"]
      .map(code)
      .join(" → ");
    const pointer = entry.soft
      ? `${code(entry.column)} (soft: no FK)`
      : code(entry.column);
    const fk = column?.organizationFk
      ? ACTION_LABEL[column.organizationFk]
      : "none";
    const composite =
      table?.compositeKeys.map((key) => code(key.column)).join(", ") || "-";
    lines.push(
      `| ${code(entry.table)} | ${path} | ${pointer} | ${fk} | ${composite} |`,
    );
  }
  lines.push("");
  return lines;
}

function renderNative(): string[] {
  const backfilled = new Set(ORGANIZATION_BACKFILL.map((entry) => entry.table));
  const { tenant } = classifyTables();
  const lines = [
    "| Table | Organization column | FK to organization |",
    "| --- | --- | --- |",
  ];
  for (const table of tenant) {
    if (backfilled.has(table.name)) continue;
    const columns = table.tenantColumns
      .map((column) => code(column.name))
      .join(", ");
    const fks = table.tenantColumns
      .map((column) =>
        column.organizationFk ? ACTION_LABEL[column.organizationFk] : "none",
      )
      .join(", ");
    lines.push(`| ${code(table.name)} | ${columns} | ${fks} |`);
  }
  lines.push("");
  return lines;
}

function renderPairs(): string[] {
  const lines: string[] = [];
  const uniques = listTenancy().filter(
    (table) => table.orgIdUniques.length > 0,
  );
  lines.push(
    `Parents that expose ${uniques.length} \`UNIQUE (id, organization)\` targets:`,
    "",
    ...uniques.flatMap((table) =>
      table.orgIdUniques.map(
        (unique) =>
          `- ${code(table.name)}: ${code(unique.name)} on (${code("id")}, ${code(unique.orgColumn)})`,
      ),
    ),
    "",
  );
  const pairs = listTenancy().flatMap((table) => table.compositeKeys);
  lines.push(
    `${pairs.length} composite foreign keys \`(pointer, organization_id) → parent (id, organization)\`; each repeats the delete action of the single-column key beside it:`,
    "",
    ...pairs.map(
      (pair) =>
        `- ${code(pair.table)}.${code(pair.column)} → ${code(pair.parent)} (${code("id")}, ${code(pair.parentOrgColumn)}): ${ACTION_LABEL[pair.onDelete]}`,
    ),
    "",
  );
  const skipped = unpairedPointers();
  lines.push(
    "Skipped on purpose: nullable pointers that are set to NULL when their target is deleted. A composite `SET NULL` would also null `organization_id`, so they stay single-column references:",
    "",
    ...skipped.map(
      (pointer) =>
        `- ${code(pointer.table)}.${code(pointer.column)} → ${code(pointer.parent)}`,
    ),
    "",
  );
  return lines;
}

function renderTenancyBlock(): string {
  const { tenant, global } = classifyTables();
  const total = listTenancy().length;
  const lines: string[] = [
    TENANCY_BEGIN,
    "",
    "<!-- Generated by `pnpm --dir packages/db tenancy:doc`; do not edit by hand. -->",
    "",
    "## Summary",
    "",
    `${total} tables: ${tenant.length} tenant (an organization column, NOT NULL), ${global.length} global (no organization column, with the reason below). ${ORGANIZATION_BACKFILL.length} tenant tables gained \`organization_id\` in migration 0118.`,
    "",
    "## Global tables",
    "",
    ...renderGlobal(),
    "## Tenant tables that gained `organization_id` in migration 0118",
    "",
    "The value was backfilled from the parent along the path shown (parents first).",
    "",
    ...renderBackfilled(),
    "## Tenant tables with their own organization column",
    "",
    ...renderNative(),
    "## Composite keys",
    "",
    ...renderPairs(),
    TENANCY_END,
  ];
  return lines.join("\n");
}

/** Replaces the generated block of `document`; throws when the markers are missing. */
export function replaceTenancyBlock(document: string): string {
  const start = document.indexOf(TENANCY_BEGIN);
  const end = document.indexOf(TENANCY_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("tenancy.md has no generated block markers");
  }
  return (
    document.slice(0, start) +
    renderTenancyBlock() +
    document.slice(end + TENANCY_END.length)
  );
}
