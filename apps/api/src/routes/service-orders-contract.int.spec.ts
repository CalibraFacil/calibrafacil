/**
 * service-orders-contract.int.spec.ts: the cloud half of the service-order
 * endpoint definitions (`packages/contracts/src/endpoints/service-orders.ts`).
 * One order is taken through intake, evaluation, quote, approval, execution and
 * back through the detail read, every client-facing endpoint is called for real
 * (real handlers, real middleware, real Postgres) and each body is parsed with
 * the response schema of its definition. `mount` also checks each body in the
 * integration tier (`checkEndpointResponses`), so a drift fails the request
 * itself; the explicit parse here names the drifting path and the status.
 *
 * Not covered here: the intake/delivery documents, the tag and their PDFs
 * (generated by background jobs), the delivery commands and the repair mark;
 * `service-orders.int.spec.ts` calls them and `mount` checks those bodies.
 * `create`, `list` and `get` of a bare order are also parsed in
 * `reference-data-contract.int.spec.ts`, against the same definitions.
 */

import { beforeEach, describe, expect, it, vi } from "vitest";
import type { z } from "zod";
import { serviceOrderEndpoints } from "@calibra-facil/contracts";
import { db } from "@calibra-facil/db";
import { asset, assetType } from "@calibra-facil/db/schema";
import { sql } from "drizzle-orm";
import { serviceOrdersRouter } from "./service-orders";
import { loginAs } from "../../test/integration/setup";
import { truncateAll } from "../../test/integration/db";
import { seedCustomer, seedOrg } from "../../test/integration/seed";
import { withStatusRepair } from "../../test/integration/state-fixtures";

vi.mock("../lib/background-jobs", () => ({
  enqueueBackgroundJob: vi.fn().mockResolvedValue({ messageId: "test-noop" }),
}));

const JSON_HEADERS = { "content-type": "application/json" };

/** Parses with the definition's response schema; the issues name the drifting path on failure. */
async function parsedBody<TSchema extends z.ZodType>(
  response: Response,
  schema: TSchema,
  expectedStatus = 200,
): Promise<z.output<TSchema>> {
  const body: unknown = await response.json();
  expect(response.status, JSON.stringify(body)).toBe(expectedStatus);
  const result = schema.safeParse(body);
  expect(result.success, JSON.stringify(result.error?.issues)).toBe(true);
  return schema.parse(body);
}

function send(method: string, body?: unknown) {
  return {
    method,
    headers: JSON_HEADERS,
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  };
}

async function seedLab() {
  const org = await seedOrg({ orgId: "org-so-contract", role: "admin" });
  loginAs({ userId: org.userId, organizationId: org.orgId });
  const customerId = await seedCustomer({
    labOrganizationId: org.orgId,
    name: "Cliente Ordens",
  });
  const [type] = await db
    .insert(assetType)
    .values({ name: "Balança", slug: "balanca-so-contract", definition: [] })
    .returning({ id: assetType.id });
  const [assetRow] = await withStatusRepair((tx) =>
    tx
      .insert(asset)
      .values({
        unitId: org.unitId,
        customerId,
        labOrganizationId: sql`(select "lab_organization_id" from "customer" where "id" = ${customerId})`,
        assetTypeId: type?.id ?? 0,
        name: "Balança analítica",
        serialNumber: "SN-SO",
        tag: "TAG-SO",
        status: "ACTIVE",
      })
      .returning({ id: asset.id }),
  );
  return { org, customerId, assetId: assetRow?.id ?? 0 };
}

describe("service-orders endpoints: real responses honor the definitions' response schemas", () => {
  beforeEach(async () => {
    await truncateAll();
  });

  it("an order through evaluation, quote, approval and execution", async () => {
    const lab = await seedLab();

    const created = await parsedBody(
      await serviceOrdersRouter.request(
        "/",
        send("POST", {
          customerId: lab.customerId,
          assetId: lab.assetId,
          claimedDefect: "Display apagado",
          intakeCondition: "Sem avarias aparentes",
        }),
      ),
      serviceOrderEndpoints.create.response,
      201,
    );
    const { id, publicId } = created.data;

    const byPublicId = await parsedBody(
      await serviceOrdersRouter.request(`/by-public-id/${publicId}`),
      serviceOrderEndpoints.getByPublicId.response,
    );
    expect(byPublicId.data.id).toBe(id);

    const communications = await parsedBody(
      await serviceOrdersRouter.request(`/${id}/communications`),
      serviceOrderEndpoints.listCommunications.response,
    );
    expect(Array.isArray(communications.data)).toBe(true);

    await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}`,
        send("PATCH", { clientVisibleNotes: "Retirar na recepção" }),
      ),
      serviceOrderEndpoints.update.response,
    );

    const evaluation = {
      diagnosis: "Célula de carga danificada",
      recommendedAction: "repair",
      requiresQuote: true,
      requiresClientApproval: true,
      calibrationRecommended: false,
      photos: [],
    };
    const evaluated = await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}/evaluations`,
        send("POST", evaluation),
      ),
      serviceOrderEndpoints.createEvaluation.response,
    );
    const evaluationId = evaluated.data?.id;
    expect(typeof evaluationId).toBe("number");

    await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}/evaluations/${evaluationId}`,
        send("PATCH", { diagnosis: "Célula de carga e cabo danificados" }),
      ),
      serviceOrderEndpoints.updateEvaluation.response,
    );

    const quote = await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}/quotes`,
        send("POST", {
          items: [
            {
              type: "service",
              description: "Troca da célula de carga",
              quantity: 1,
              unit: "un",
              unitPriceCents: 25000,
            },
          ],
        }),
      ),
      serviceOrderEndpoints.createQuote.response,
      201,
    );
    const quoteId = quote.data?.id;
    expect(typeof quoteId).toBe("number");

    const sent = await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}/quotes/${quoteId}/send`,
        send("POST", { clientMessage: "Segue o orçamento" }),
        // The portal's base URL comes from the bindings.
        { PORTAL_APP_URL: "https://portal.example.test" },
      ),
      serviceOrderEndpoints.sendQuote.response,
    );
    expect(sent.publicUrl).toContain("/service-order-access/");

    // Not client-facing (no SDK method): the lab records the customer's phone approval.
    const approved = await serviceOrdersRouter.request(
      `/${id}/quotes/${quoteId}/approve-manually`,
      send("POST", {
        approvedByName: "Cliente Teste",
        manualApprovalEvidenceType: "phone",
        manualApprovalEvidenceText: "Cliente autorizou por telefone",
      }),
    );
    expect(approved.status).toBe(200);

    await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}/execution/start`,
        send("POST", { notes: "Início do reparo" }),
      ),
      serviceOrderEndpoints.startExecution.response,
    );
    await parsedBody(
      await serviceOrdersRouter.request(
        `/${id}/execution/finish`,
        send("POST", {
          servicePerformed: "Troca da célula de carga",
          result: "repaired",
          calibrationRequiredAfterRepair: true,
        }),
      ),
      serviceOrderEndpoints.saveExecution.response,
    );

    const detail = await parsedBody(
      await serviceOrdersRouter.request(`/${id}`),
      serviceOrderEndpoints.get.response,
    );
    expect(detail.data.evaluations).toHaveLength(1);
    expect(detail.data.quotes.map((row) => row.status)).toEqual(["approved"]);
    expect(detail.data.execution).toMatchObject({
      result: "repaired",
      calibrationRequiredAfterRepair: true,
    });

    const list = await parsedBody(
      await serviceOrdersRouter.request("/?page=1&limit=20"),
      serviceOrderEndpoints.list.response,
    );
    expect(list.data.map((row) => row.publicId)).toEqual([publicId]);
  });
});
